  bedrooms          TINYINT,
  bathrooms         TINYINT,
  area_m2           DECIMAL(10,2),
  price             DECIMAL(14,2),
  FOREIGN KEY (neighborhood_id) REFERENCES neighborhoods(neighborhood_id)
);

