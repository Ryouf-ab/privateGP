CREATE TABLE IF NOT EXISTS neighborhoods (
  neighborhood_id        INT PRIMARY KEY,
  name_ar                VARCHAR(100) NOT NULL UNIQUE,
  name_en                VARCHAR(100),               -- RCRC spelling, e.g. AL-MALQA
  region                 VARCHAR(20),                -- شمال / جنوب / شرق / غرب / وسط / الدرعية
  latitude               DECIMAL(9,6),
  longitude              DECIMAL(9,6),
  schools_count          INT DEFAULT 0,              -- MOE (school + stage)
  schools_primary        INT DEFAULT 0,
  schools_middle         INT DEFAULT 0,
  schools_secondary      INT DEFAULT 0,
  hospitals_count        INT DEFAULT 0,
  parks_count            INT DEFAULT 0,
  gyms_count             INT DEFAULT 0,
  pharmacies_count       INT DEFAULT 0,
  supermarkets_count     INT DEFAULT 0,              -- RCRC supermarkets + hypermarkets + grocery
  shopping_centers_count INT DEFAULT 0,
  banks_count            INT DEFAULT 0,
  fuel_stations_count    INT DEFAULT 0,
  metro_stations_count   INT DEFAULT 0,
  median_price_m2        DECIMAL(10,0),              -- MOJ residential deals
  deals_count            INT DEFAULT 0,
  median_property_price  DECIMAL(12,0),              -- Aqar listings, all types
  median_apartment_price DECIMAL(12,0),
  median_villa_price     DECIMAL(12,0),
  median_floor_price     DECIMAL(12,0),
  listings_count         INT DEFAULT 0
);

CREATE TABLE IF NOT EXISTS properties (
  property_id       VARCHAR(20) PRIMARY KEY,
